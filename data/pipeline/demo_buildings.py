"""Issue #44: data/demo/buildings.json (DemoBuilding, CONTRACTS.md plan v2) + a map GeoJSON for the 3D view.

Inputs (all generated by the pipeline, gitignored): area_hollywood_structures.json, area_hollywood_assessor.json,
buildings_hollywood.json. Never commit the outputs: they contain sponsor data and this repo is public.

Run: python3 data/pipeline/demo_buildings.py
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from export_layers import simplify  # noqa: E402

DATA = Path(__file__).resolve().parents[1]
PROC, DEMO = DATA / "processed", DATA / "demo"

# SimConfig defaults (CONTRACTS.md). Labeled assumptions, shown in the UI.
HOUSEHOLD_SIZE = 2.4
DEFAULT_VACANCY = 0.05
NEED_RATE = 0.10
SENIOR_NEED_RATE = 0.5
STORY_M = 3.2
TYPE_HEIGHT_M = {"single_family": 6.0, "multiple_family": 10.0, "commercial": 8.0, "institutional_buildings": 9.0,
                 "shed": 3.0, "garages_carports": 3.0}
NO_PEOPLE_TYPES = {"shed", "garages_carports"}
SQFT_TO_M2 = 0.092903


def use_of(vx_type, assessor_use):
    if vx_type in NO_PEOPLE_TYPES:
        return "none"
    if assessor_use == "Residential":
        return "residential"
    if assessor_use in ("Commercial", "Industrial"):
        return "commercial"
    if vx_type in ("single_family", "multiple_family"):
        return "residential"
    return "other"


def write_atomic(path: Path, obj):
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(obj, separators=(",", ":")))
    os.replace(tmp, path)


def main():
    DEMO.mkdir(exist_ok=True)
    structs = json.loads((PROC / "area_hollywood_structures.json").read_text())
    assessor = json.loads((PROC / "area_hollywood_assessor.json").read_text())
    hb = json.loads((PROC / "buildings_hollywood.json").read_text())
    costar_of = {s["id"]: s.get("costar_id") for s in hb["structures"]}
    costar = hb["costar"]

    # Assessor units/area are per parcel: give them to the parcel's largest primary structure only.
    owner = {}
    for s in structs:
        a = assessor.get(s["id"])
        if not a or not a.get("ain"):
            continue
        cur = owner.get(a["ain"])
        key = (bool(s.get("primary-structure")), s.get("footprint.area") or 0)
        if cur is None or key > cur[0]:
            owner[a["ain"]] = (key, s["id"])
    owner_ids = {v[1] for v in owner.values()}
    # CoStar units likewise go to one structure per CoStar property (its largest).
    cs_owner = {}
    for s in structs:
        c = costar_of.get(s["id"])
        if c and (c not in cs_owner or (s.get("footprint.area") or 0) > cs_owner[c][0]):
            cs_owner[c] = (s.get("footprint.area") or 0, s["id"])
    cs_owner_ids = {v[1] for v in cs_owner.values()}

    buildings, feats = [], []
    for s in structs:
        a = assessor.get(s["id"]) or {}
        cid = costar_of.get(s["id"])
        c = costar.get(cid) if cid else None
        vx_type = s.get("building-type.class")
        use = use_of(vx_type, a.get("use_type"))
        foot = s.get("footprint.area") or 0

        stories = (c or {}).get("stories")
        if not stories and a.get("floor_area_sqft") and foot > 20 and s["id"] in owner_ids:
            est = a["floor_area_sqft"] * SQFT_TO_M2 / foot
            # Parcel floor area can belong to several buildings; a small footprint must not become a tower.
            cap = 3 if foot < 80 else (6 if foot < 250 else 40)
            stories = max(1, min(cap, round(est)))
        height = round(stories * STORY_M, 1) if stories else TYPE_HEIGHT_M.get(vx_type, 6.0)

        units = None
        if c and s["id"] in cs_owner_ids:
            units = c.get("units")
        if units is None and s["id"] in owner_ids and not (c and cid in cs_owner):
            units = a.get("units")
        if use == "none" or use != "residential":
            units = units if use == "residential" else None
        vacancy = ((c or {}).get("vacancy_pct") or DEFAULT_VACANCY * 100) / 100
        people = round(units * HOUSEHOLD_SIZE * (1 - vacancy)) if units else 0
        need_rate = SENIOR_NEED_RATE if (c or {}).get("is_senior") else NEED_RATE
        if c and c.get("is_walkup") and (stories or 0) >= 3:
            need_rate *= 1.5
        need = round(people * need_rate)

        ring = simplify([[round(pt[1], 6), round(pt[0], 6)] for pt in s["rings"][0]])
        b = {"id": s["id"], "lat": s["lat"], "lng": s["lng"], "footprint": ring, "height_m": height,
             "ground_elevation_m": s.get("ground-elevation.value"), "use": use, "units": units,
             "people_est": people, "people_need_help_est": need, "fire_arrival_min": None,
             "costar": None, "matterport_ids": []}
        if c:
            b["costar"] = {"id": c["id"], "name": c["name"], "address": c["address"], "stories": c.get("stories"),
                           "units": c.get("units"), "is_walkup": c.get("is_walkup"), "elevators": c.get("elevators"),
                           "is_senior": bool(c.get("is_senior")),
                           "manager": {"company": (c.get("manager") or {}).get("company"),
                                       "phone": (c.get("manager") or {}).get("phone")}}
        buildings.append(b)
        feats.append({"type": "Feature", "geometry": {"type": "Polygon", "coordinates": [ring]},
                      "properties": {"id": s["id"], "h": height, "use": use, "people": people, "need": need,
                                     "costar": 1 if c else 0, "name": (c or {}).get("name") or a.get("address"),
                                     "units": units, "stories": stories}})

    write_atomic(DEMO / "buildings.json", {"buildings": buildings})
    write_atomic(DEMO / "buildings_map.geojson", {"type": "FeatureCollection", "features": feats})
    tot = sum(b["people_est"] for b in buildings)
    print(f"{len(buildings)} buildings, {sum(1 for b in buildings if b['costar'])} with CoStar, "
          f"people_est total {tot:,}, need help {sum(b['people_need_help_est'] for b in buildings):,}")
    print("heights: median", sorted(b["height_m"] for b in buildings)[len(buildings) // 2],
          "max", max(b["height_m"] for b in buildings))


if __name__ == "__main__":
    main()
